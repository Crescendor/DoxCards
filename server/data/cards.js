// Helper to get shuffled decks
export function getDeck(type = 'all') {
  let white = [...WHITE_CARDS];
  let red = [...RED_FLAGS_CARDS];

  return {
    white: shuffleArray(white),
    red: shuffleArray(red)
  };
}

function shuffleArray(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}
